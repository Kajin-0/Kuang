"""No-network tests for reviewed CC0 drum source selection and native sampler bindings."""
import copy
import json
import math
import os
import tempfile
import unittest
import wave
from pathlib import Path

from kuang.house_sources import _source_candidates, _to_48k_pcm, prepare_kit
from kuang.house_template import template
from kuang.sample_assets import pcm_info, read_asset
from kuang.schema import ValidationError, dumps, validate
from kuang.song import rules_plan


class HouseSourceTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.pack = self.root / "house-core"
        self.pack.mkdir()
        (self.pack / "LICENSE").write_text("CC0 1.0 Universal\n")
        (self.pack / "LICENSES.md").write_text("CC0 samples generated by fixture.\n")
        samples = {}
        roles = {
            "kick": ("deep", "warm", "round"),
            "clap": ("classic", "tight", "dry"),
            "hat_closed": ("closed", "dark", "tight"),
            "hat_open": ("open", "airy", "bright"),
            "perc": ("shaker", "driving", "tight"),
        }
        for role, (name, first, second) in roles.items():
            for index in range(2):
                key = f"house.{role}.{name}-{index}"
                relative = f"samples/{role}-{index}.wav"
                wav = self.pack / relative
                wav.parent.mkdir(exist_ok=True)
                f = 110 + index * 110
                data = bytearray()
                for n in range(6000):
                    sample = round(9500 * math.sin(2*math.pi*f*n/44100) *
                                   math.exp(-n/2000))
                    data.extend(sample.to_bytes(2, "little", signed=True))
                with wave.open(str(wav), "wb") as w:
                    w.setnchannels(1); w.setsampwidth(2); w.setframerate(44100)
                    w.writeframes(data)
                samples[key] = {"path": relative, "type": role,
                                "character_tags": [first, second] if index == 0 else
                                                  [second],
                                "license_source": "Own synthesized CC0 sample"}
        self.samples = samples
        (self.pack/"manifest.json").write_text(json.dumps({
            "name":"house-core","license":"CC0-1.0","samples":samples}))

    def tearDown(self):
        self.tmp.cleanup()

    def test_opt_in_approved_kick_is_license_audited_and_gain_bounded(self):
        """Explicit approved Phase sample must be in the locally audited pack."""
        import hashlib
        source=self.pack/"samples/kick-1.wav"
        self.samples["house.kick.punch-02"]={
            "path":"samples/kick-1.wav","type":"kick",
            "character_tags":["punchy","solid"],
            "license_source":"Own synthesized CC0 sample"}
        (self.pack/"manifest.json").write_text(json.dumps({
            "name":"house-core","license":"CC0-1.0","samples":self.samples}))
        spec,_=rules_plan("deep house in C minor 16 bars",41)
        project,_=template(spec,profile="deep",harmony_profile="simple",
                            impact_pocket=True,include_pad=False)
        original,_,_=prepare_kit(project,self.pack,self.root/"original-kit","deep",0)
        impact,assets,evidence=prepare_kit(
            project,self.pack,self.root/"impact-kit","deep",0,impact_pocket=True)
        validate(impact)
        self.assertEqual(evidence["kick"]["source_id"],"house.kick.punch-02")
        self.assertEqual(evidence["groove_impact_pocket"]["kick_relative_gain_delta_db"],8.)
        t=next(t for t in impact.tracks if t.id=="track-kick")
        old=next(t for t in original.tracks if t.id=="track-kick")
        self.assertEqual(t.controls["mixer.gain_db"],old.controls["mixer.gain_db"]+8)
        self.assertEqual(t.clips,old.clips)
        self.assertEqual(evidence["kick"]["resample"]["src_sha256"],
                         hashlib.sha256(source.read_bytes()).hexdigest())
        for role in ("track-bass","track-harmony","track-snare"):
            a=next(t for t in impact.tracks if t.id==role)
            b=next(t for t in original.tracks if t.id==role)
            self.assertEqual(a.clips,b.clips)
        with self.assertRaisesRegex(ValidationError,"punch-02"):
            self._bad_reference_kit(project)

    def _bad_reference_kit(self,project):
        # Keep all other fixture sources; eliminate explicit approved kick.
        new=dict(self.samples)
        del new["house.kick.punch-02"]
        (self.pack/"manifest.json").write_text(json.dumps({
            "name":"house-core","license":"CC0-1.0","samples":new}))
        prepare_kit(project,self.pack,self.root/"bad-kit","deep",0,impact_pocket=True)

    def test_opt_in_identity_uses_profile_kick_not_global_phase44_kick(self):
        # Demonstrate that the new generator is not forced to sound like the
        # same source pairing for unrelated house profiles.
        self.samples["house.kick.punch-02"]={
            "path":"samples/kick-1.wav","type":"kick",
            "character_tags":["punchy","solid"],
            "license_source":"Own synthesized CC0 sample"}
        (self.pack/"manifest.json").write_text(json.dumps({
            "name":"house-core","license":"CC0-1.0","samples":self.samples}))
        spec,_=rules_plan("deep house in C minor 16 bars",43)
        legacy,_=template(spec,profile="deep",impact_pocket=True)
        new,_=template(spec,profile="deep",impact_pocket=True,
                       groove_identity_v2=True)
        _,_,first=prepare_kit(legacy,self.pack,self.root/"old-kit","deep",
                              impact_pocket=True)
        _,_,second=prepare_kit(new,self.pack,self.root/"identity-kit","deep",
                               impact_pocket=True,groove_identity_v2=True)
        self.assertEqual(first["kick"]["source_id"],"house.kick.punch-02")
        self.assertEqual(second["kick"]["source_id"],"house.kick.deep-0")
        self.assertNotEqual(first["kick"]["source_id"],second["kick"]["source_id"])
        self.assertTrue(second["kick"]["source_kind"].startswith("locally provided"))
        with self.assertRaises(ValidationError):
            prepare_kit(new,self.pack,self.root/"bad-identity-kit","deep",
                        impact_pocket=False,groove_identity_v2=True)

    def test_exact_deterministic_resample_and_valid_native_format(self):
        source = self.pack / "samples/kick-0.wav"
        a = self.root / "first.wav"
        b = self.root / "second.wav"
        first = _to_48k_pcm(source, a)
        second = _to_48k_pcm(source, b)
        self.assertEqual(first, second)
        self.assertEqual(a.read_bytes(), b.read_bytes())
        self.assertEqual(first["rate_in"], 44100)
        self.assertEqual(first["rate_out"], 48000)
        self.assertEqual(pcm_info(a)["sample_rate"], 48000)
        self.assertEqual(pcm_info(a)["bits_per_sample"], 24)
        self.assertEqual(first["wav_sha256"], second["wav_sha256"])

    def test_two_candidate_roles_and_groove_is_preserved(self):
        spec, _ = rules_plan("deep house in C minor, 8 bars", 17)
        original, proof = template(spec, profile="deep", harmony_profile="simple")
        candidates = _source_candidates(self.pack, "deep")
        self.assertEqual(set(candidates), {"kick","snare","hats","open_hat","percussion"})
        a, roots, ar = prepare_kit(original, self.pack, self.root/"libraryA", "deep", 0)
        b, _, br = prepare_kit(original, self.pack, self.root/"libraryB", "deep", 1)
        validate(a); validate(b)
        self.assertNotEqual(ar["kick"]["source_id"], br["kick"]["source_id"])
        self.assertEqual(set(roots), {"track-kick","track-snare","track-hats","track-open_hat","track-percussion"})
        for track in original.tracks:
            other = next(t for t in a.tracks if t.id == track.id)
            if track.id == "track-hats":
                # Moving existing MIDI 46 into its own editable sampler track
                # must not change the combined note events.
                opened = next(t for t in a.tracks if t.id == "track-open_hat")
                original_events = [(c.start+n.start,n.pitch,n.velocity) for c in track.clips for n in c.notes]
                combined = sorted([(c.start+n.start,n.pitch,n.velocity) for t in (other,opened)
                                   for c in t.clips for n in c.notes])
                self.assertEqual(sorted(original_events), combined)
            else:
                self.assertEqual(track.clips, other.clips)
        self.assertNotEqual(dumps(original), dumps(a))
        self.assertNotEqual(dumps(a), dumps(b))
        for role, root in roots.items():
            m = read_asset(root)
            self.assertEqual(m["provenance"]["license"], "CC0-1.0")
            self.assertTrue(m["provenance"]["redistribution_permitted"])
            self.assertFalse(m["mapping"]["key_tracking"])
            self.assertEqual(m["mapping"]["playback"], "one_shot")
            track = next(t for t in a.tracks if t.id == role)
            self.assertEqual(track.instrument.plugin_ref, "soundcraft:sampler")
            self.assertTrue(track.instrument.preset_ref.startswith("sha256:"))
        self.assertEqual(original.metadata["composer"], a.metadata["composer"])
        self.assertEqual(proof["harmony"]["profile"], "simple")

    def test_full_arranger_preserves_independent_cc0_open_hat_role(self):
        """Regression: source splitting a hat sampler must survive long form."""
        from kuang.house_full_arranger import arrange_full_song
        from kuang.schema import state_hash
        spec,_=rules_plan("deep house in D minor, 32 bars",51)
        nucleus,_=template(spec,profile="deep",harmony_profile="simple",
                            include_pad=False)
        bound,assets,receipt=prepare_kit(nucleus,self.pack,self.root/"full-kit","deep",0)
        prior=state_hash(bound)
        p,evidence=arrange_full_song(bound,bars=96,profile="deep",seed=51)
        validate(p)
        self.assertEqual(state_hash(bound),prior)
        self.assertTrue(evidence["technical_pass"])
        self.assertIn("track-open_hat",{t.id for t in p.tracks})
        open_hat=next(t for t in p.tracks if t.id=="track-open_hat")
        self.assertEqual(open_hat.instrument.plugin_ref,"soundcraft:sampler")
        self.assertGreater(sum(len(c.notes) for c in open_hat.clips),0)
        self.assertTrue(all(n.pitch==46 for c in open_hat.clips for n in c.notes))
        sections={s["name"]:s["events"] for s in evidence["sections"]}
        self.assertGreater(sections["Groove A"]["open_hat"],0)
        self.assertGreater(sections["Main Drop"]["open_hat"],0)
        self.assertEqual(p.bars,96)
        self.assertEqual(set(assets),
                         {"track-kick","track-snare","track-hats",
                          "track-open_hat","track-percussion"})

    def test_minimal_profile_omits_inactive_percussion_without_invented_hits(self):
        from kuang.house_full_arranger import arrange_full_song
        spec, _ = rules_plan("minimal house in D minor, 32 bars", 17)
        source, _ = template(spec, profile="minimal", harmony_profile="simple",
                             include_pad=False)
        long, _ = arrange_full_song(source, bars=96, profile="minimal", seed=17)
        self.assertNotIn("track-percussion", {t.id for t in long.tracks})
        bound, bindings, receipt = prepare_kit(long, self.pack,
                                                self.root/"minimal-kit", "minimal", 0)
        validate(bound)
        self.assertNotIn("percussion", receipt)
        self.assertEqual(set(bindings), {"track-kick","track-snare","track-hats","track-open_hat"})
        self.assertNotIn("track-percussion", {t.id for t in bound.tracks})
        self.assertEqual(long.bars, bound.bars)

    def test_out_of_scope_and_untrusted_source_rejected(self):
        spec, _ = rules_plan("house, 8 bars", 17)
        project, _ = template(spec, profile="straight")
        for profile, index in (("future", 0), ("deep", 3), ("deep", True)):
            with self.subTest(profile=profile,index=index):
                with self.assertRaises(ValidationError):
                    prepare_kit(project, self.pack, self.root/"bad", profile, index)
        malicious = copy.deepcopy(self.samples)
        malicious["house.kick.deep-0"]["path"] = "../outside.wav"
        (self.pack/"manifest.json").write_text(json.dumps({
            "name":"house-core","license":"CC0-1.0","samples":malicious}))
        with self.assertRaisesRegex(ValidationError, "relative"):
            _source_candidates(self.pack, "deep")

    def test_missing_license_rejected(self):
        (self.pack/"LICENSES.md").unlink()
        with self.assertRaisesRegex(ValidationError, "licens"):
            _source_candidates(self.pack, "deep")

    def test_nonconforming_source_audio_rejected(self):
        source = self.pack / "samples/kick-0.wav"
        with wave.open(str(source),"rb") as w:
            pcm=w.readframes(w.getnframes())
        with wave.open(str(source),"wb") as w:
            w.setnchannels(1);w.setsampwidth(2);w.setframerate(48000);w.writeframes(pcm)
        with self.assertRaisesRegex(ValidationError, "44100"):
            _to_48k_pcm(source, self.root/"bad.wav")
